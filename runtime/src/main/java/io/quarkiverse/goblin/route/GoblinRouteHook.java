/**
 * Extends the {@link ChaosLayer#HTTP_IN} layer to reactive routes ({@code @Route} methods, issue #64).
 * <p>
 * {@code GoblinChaosFilter} is a JAX-RS filter, so it never sees a request served by a reactive route. Instead, the
 * deployment module weaves a call to {@link #beforeInvoke(Handler, RoutingContext)} into
 * {@code io.quarkus.vertx.web.runtime.RouteHandler.handle()}, right before the generated handler invokes the route
 * method -- after the CDI request context is activated, so the layer decision made here is visible to the service and
 * database hooks below the route. Quarkus REST requests never go through a {@code RouteHandler}, so a REST request is
 * still assaulted exactly once, by the JAX-RS filter.
 * <p>
 * The same configuration drives both entry points: the per-request layer resolution, the {@code goblin.target} rules,
 * the assault order (latency, exception, HTTP status, dependency degradation) and the history labels, so a
 * reactive-route assault is indistinguishable from a REST one. For the response header and body assaults, the route
 * method receives a routing context whose response applies them (see {@link RouteResponse}).
 * <p>
 * A reactive route usually runs on the event loop, which must never block. The latency is then applied with a Vert.x
 * timer, and the route method runs once the delay has elapsed; on a worker or virtual thread ({@code @Blocking},
 * {@code type = BLOCKING}, {@code @RunOnVirtualThread}) the thread sleeps, like the REST path.
 * <p>
 * Failure handlers ({@code type = FAILURE}) and {@code @RouteFilter} methods are never assaulted: the former exist to
 * handle failures, the latter are plumbing, not endpoints.
 */
public final class GoblinRouteHook {

    private static final Logger LOG = Logger.getLogger(GoblinRouteHook.class);

    /**
     * Routing-context key marking a request already seen by the hook, so the route method invoked after a deferred
     * latency, or a second route reached through {@code next()}, is never assaulted again.
     */
    static final String HANDLED = "io.quarkiverse.goblin.route.handled";

    /** Infix of the handler classes generated by Quarkus for {@code @Route} methods. */
    static final String HANDLER_INFIX = "_RouteHandler_";

    private static final String ROUTE = "io.quarkus.vertx.web.Route";
    private static final String ROUTES = "io.quarkus.vertx.web.Route$Routes";
    private static final String ROUTE_BASE = "io.quarkus.vertx.web.RouteBase";

    /**
     * The route method behind each generated handler class, resolved once. Held per class, so the handlers of a
     * previous dev-mode generation are collected with their class loader.
     */
    private static final ClassValue<RouteTarget> TARGETS = new ClassValue<>() {
        @Override
        protected RouteTarget computeValue(Class<?> handlerClass) {
            return resolve(handlerClass);
        }
    };

    private GoblinRouteHook() {
    }

    /**
     * The targeting decision for one route method.
     *
     * @param description the history identifier, e.g. {@code "GreetingRoutes.hello"}
     * @param eligible whether the route may be assaulted at the HTTP_IN layer
     * @param excluded whether the route sits in an excluded package, which shields the whole request
     * @param json whether the route answers JSON, so an abort body stays parseable
     * @param invoker the public {@code RouteHandler.invoke(RoutingContext)} method, which runs the route method itself
     */
    record RouteTarget(String description, boolean eligible, boolean excluded, boolean json, Method invoker) {
    }

    /**
     * The decision made for a request by the first {@code @Route} it reached, kept in the routing context under
     * {@link #HANDLED} so a REST resource reached behind a pass-through route applies the same decision on its own
     * thread.
     *
     * @param layer the resolved assault layer, or {@code null} when none (or when chaos is off)
     * @param shielded whether the route sits in an excluded package
     * @param httpIn whether the route was selected for HTTP_IN assaults
     * @param description the history identifier of the route
     */
    public record RouteDecision(ChaosLayer layer, boolean shielded, boolean httpIn, String description) {
    }

    /** Marks a handler that is not backed by a {@code @Route} method (e.g. a {@code @RouteFilter}). */
    private static final RouteTarget NOT_A_ROUTE = new RouteTarget(null, false, false, false, null);

    private static final String ROUTE_HANDLER = "io.quarkus.vertx.web.runtime.RouteHandler";

    private static final AtomicBoolean SKIPPED_LATENCY_WARNED = new AtomicBoolean();

    /**
     * Called by the woven {@code RouteHandler.handle()} right before the route method is invoked.
     *
     * @param handler the generated route handler
     * @param context the routing context of the request
     * @return the routing context to invoke the route method with now -- {@code context} itself, or a wrapper rewriting
     *         the response body -- or {@code null} when Goblin took the request over (aborted it, or deferred it behind a
     *         latency timer that invokes the route method once the delay elapsed)
     */
    public static RoutingContext beforeInvoke(Handler<RoutingContext> handler, RoutingContext context) {
        try {
            return apply(handler, context);
        } catch (RuntimeException | LinkageError e) {
            // never let a Goblin defect break the application's routes
            LOG.debugf(e, "Goblin: reactive route hook failed, invoking the route unchanged");
            return context;
        }
    }

    private static RoutingContext apply(Handler<RoutingContext> handler, RoutingContext request) {
        RoutingContext context = request;
        if (context.failed()) {
            return context;
        }
        Object previous = context.get(HANDLED);
        if (previous != null && !inheritsHttpIn(previous)) {
            return context;
        }
        RouteTarget target = TARGETS.get(handler.getClass());
        if (target == NOT_A_ROUTE) {
            return context;
        }
        AssaultEngine engine = engine();
        ChaosLayer assaultLayer;
        if (previous != null) {
            // a route in front, spared by the targeting rules, drew HTTP_IN: this route takes that draw
            if (engine == null || !engine.isActive()) {
                return context;
            }
            assaultLayer = ChaosLayer.HTTP_IN;
        } else {
            // never let a decision left over on this event-loop or worker thread leak into this request
            ChaosRequestContext.clear();
            if (engine == null || !engine.isActive()) {
                context.put(HANDLED, new RouteDecision(null, false, false, target.description()));
                return context;
            }
            if (target.excluded()) {
                context.put(HANDLED, new RouteDecision(null, true, false, target.description()));
                ChaosRequestContext.shield();
                return context;
            }
            assaultLayer = engine.resolveAssaultLayer();
        }
        ChaosRequestContext.setAssaultLayer(assaultLayer);
        boolean httpIn = assaultLayer == ChaosLayer.HTTP_IN && target.eligible();
        context.put(HANDLED, new RouteDecision(assaultLayer, false, httpIn, target.description()));
        LOG.debugf("Goblin: reactive route request resolved to %s layer for %s", assaultLayer, target.description());
        if (!httpIn) {
            return context;
        }
        MutableAssaultConfig config = engine.configSnapshot();
        if (config == null) {
            return context;
        }
        if (config.isResponseBodyEnabled() || config.isResponseHeaderEnabled()) {
            context = RouteResponse.wrap(context, config, engine, target.description());
        }
        if (config.isLatencyEnabled()) {
            long delay = LatencySupport.drawDelay(config);
            LOG.debugf("Goblin: injecting latency (%d ms) on reactive route %s", delay, target.description());
            if (delay < 1) {
                // Vert.x refuses a timer under 1 ms: nothing to wait for
                engine.recordAssault(target.description(), "latency", delay);
            } else if (!LatencySupport.isBlockingAllowed()) {
                Vertx vertx = currentVertx();
                if (vertx != null) {
                    // the request context is active here: capture it so the route method runs inside it after the delay
                    ManagedContext requestContext = Arc.container().requestContext();
                    InjectableContext.ContextState state = requestContext.getState();
                    RoutingContext delayed = context;
                    vertx.setTimer(delay,
                            id -> resume(handler, delayed, requestContext, state, engine, config, target, delay));
                    return null;
                }
                // a non-blocking thread outside any Vert.x context: neither a sleep nor a timer is possible
                if (SKIPPED_LATENCY_WARNED.compareAndSet(false, true)) {
                    LOG.warnf("Goblin: skipping %d ms latency on reactive route %s: no Vert.x context to schedule it on "
                            + "(further occurrences are logged at DEBUG)", delay, target.description());
                } else {
                    LOG.debugf("Goblin: skipping %d ms latency on reactive route %s", delay, target.description());
                }
            } else {
                sleep(delay, target.description());
                engine.recordAssault(target.description(), "latency", delay);
            }
        }
        return abort(context, engine, config, target) ? null : context;
    }

    /**
     * {@code exclude-annotations} and {@code include-packages} only spare the route they select, not the whole request:
     * when such a route (typically a pass-through filter calling {@code next()}) drew HTTP_IN, the next route of the
     * request takes that draw instead of drawing again.
     *
     * @param previous the decision already stored for the request
     * @return {@code true} when the current route must apply the HTTP_IN draw of a spared route in front of it
     */
    private static boolean inheritsHttpIn(Object previous) {
        return previous instanceof RouteDecision decision && decision.layer() == ChaosLayer.HTTP_IN && !decision.httpIn()
                && !decision.shielded();
    }

    /**
     * Continues a request deferred by the latency timer: records the latency, applies the aborting assaults, otherwise
     * invokes the route method inside the request context captured before the delay. {@code RouteHandler.handle()} is
     * not called again, so the security identity is not set nor its event fired a second time.
     */
    private static void resume(Handler<RoutingContext> handler, RoutingContext context, ManagedContext requestContext,
            InjectableContext.ContextState state, AssaultEngine engine, MutableAssaultConfig config, RouteTarget target,
            long delay) {
        HttpServerResponse response = context.response();
        if (response.ended() || response.closed()) {
            // the client went away during the delay: nothing was assaulted
            return;
        }
        engine.recordAssault(target.description(), "latency", delay);
        try {
            if (abort(context, engine, config, target)) {
                return;
            }
            requestContext.activate(state);
            // another request may have used this event loop meanwhile: restore this request's decision
            ChaosRequestContext.setAssaultLayer(ChaosLayer.HTTP_IN);
            try {
                target.invoker().invoke(handler, context);
            } finally {
                requestContext.deactivate();
            }
        } catch (Throwable t) {
            Throwable failure = t instanceof InvocationTargetException invocation && invocation.getCause() != null
                    ? invocation.getCause()
                    : t;
            if (!context.failed() && !response.ended()) {
                context.fail(failure);
            }
        }
    }

    /**
     * Returns the decision of the reactive route the current request already went through, typically a {@code @Route}
     * acting as a pass-through filter that calls {@code next()} in front of a REST resource: the request was assaulted
     * there, so the JAX-RS filter applies this decision instead of making a second one.
     *
     * @return the decision, or {@code null} when the current request was not seen by this hook
     */
    public static RouteDecision currentRequestDecision() {
        try {
            ArcContainer container = Arc.container();
            if (container == null || !container.requestContext().isActive()) {
                return null;
            }
            InstanceHandle<RoutingContext> current = container.instance(RoutingContext.class);
            RoutingContext context = current.isAvailable() ? current.get() : null;
            return context != null && context.get(HANDLED) instanceof RouteDecision decision ? decision : null;
        } catch (RuntimeException | LinkageError e) {
            return null;
        }
    }

    /**
     * Applies the aborting assaults in the REST order: exception, then HTTP status, then dependency degradation.
     *
     * @return {@code true} when the request was aborted and the route method must not run
     */
    private static boolean abort(RoutingContext context, AssaultEngine engine, MutableAssaultConfig config,
            RouteTarget target) {
        if (config.isExceptionEnabled()) {
            LOG.debugf("Goblin: injecting exception on reactive route %s", target.description());
            engine.recordAssault(target.description(), "exception");
            // the failure handlers of the router (including @Route(type = FAILURE) methods) answer it
            context.fail(ExceptionAssault.createException(config));
            return true;
        }
        if (config.isHttpStatusEnabled()) {
            LOG.debugf("Goblin: forcing HTTP %d on reactive route %s", config.getHttpStatusCode(), target.description());
            engine.recordAssault(target.description(), "http-status");
            end(context, config.getHttpStatusCode(), config.getHttpStatusMessage(), target);
            return true;
        }
        if (config.isDependencyDegradationEnabled()) {
            LOG.debugf("Goblin: simulating dependency degradation on reactive route %s", target.description());
            engine.recordAssault(target.description(), "dependency-degradation");
            end(context, 503, AbortResponses.DEPENDENCY_MESSAGE, target);
            return true;
        }
        return false;
    }

    private static void end(RoutingContext context, int status, String message, RouteTarget target) {
        HttpServerResponse response = context.response();
        if (response.ended() || response.closed()) {
            return;
        }
        String safeMessage = message != null ? message : "";
        response.setStatusCode(status);
        if (target.json()) {
            response.putHeader("Content-Type", "application/json").end(AbortResponses.jsonBody(safeMessage, status));
        } else {
            response.putHeader("Content-Type", "text/plain").end(safeMessage);
        }
    }

    private static void sleep(long delay, String description) {
        try {
            LatencySupport.sleep(delay, description);
        } catch (InterruptedException e) {
            // interrupt flag restored by LatencySupport: let the request proceed without the remaining delay
        }
    }

    /**
     * Resolves the route method behind a generated handler class, named
     * {@code <bean class>_RouteHandler_<method name>_<sha1>} by the Quarkus reactive routes extension.
     *
     * @param handlerClass the generated handler class
     * @return the targeting decision, or {@link #NOT_A_ROUTE}
     */
    static RouteTarget resolve(Class<?> handlerClass) {
        String[] names = parseHandlerName(handlerClass.getName());
        if (names == null) {
            return NOT_A_ROUTE;
        }
        Class<?> beanClass;
        try {
            beanClass = Class.forName(names[0], false, handlerClass.getClassLoader());
        } catch (ClassNotFoundException | LinkageError e) {
            return NOT_A_ROUTE;
        }
        Method method = findRouteMethod(beanClass, names[1]);
        Method invoker = findInvoker(handlerClass);
        if (method == null || invoker == null) {
            return NOT_A_ROUTE;
        }
        RouteTarget target = target(method, targetRules());
        return new RouteTarget(target.description(), target.eligible(), target.excluded(), target.json(), invoker);
    }

    /**
     * @param handlerClassName the generated handler class name
     * @return the bean class name and the method name, or {@code null} when the name does not follow the convention
     */
    static String[] parseHandlerName(String handlerClassName) {
        int infix = handlerClassName.lastIndexOf(HANDLER_INFIX);
        if (infix <= 0) {
            return null;
        }
        String rest = handlerClassName.substring(infix + HANDLER_INFIX.length());
        int hash = rest.lastIndexOf('_');
        if (hash <= 0) {
            return null;
        }
        return new String[] { handlerClassName.substring(0, infix), rest.substring(0, hash) };
    }

    /**
     * Applies the targeting rules to a route method, exactly like the JAX-RS filter does for a resource method: its
     * package, then the annotations of the method and of its declaring class.
     */
    static RouteTarget target(Method method, TargetRules rules) {
        Class<?> declaringClass = method.getDeclaringClass();
        String packageName = declaringClass.getPackageName();
        boolean eligible = rules.isPackageTargeted(packageName)
                && !rules.isExcludedBy(annotationNames(method.getAnnotations()))
                && !rules.isExcludedBy(annotationNames(declaringClass.getAnnotations()));
        return new RouteTarget(declaringClass.getSimpleName() + "." + method.getName(), eligible,
                rules.isPackageExcluded(packageName),
                AbortResponses.routeWantsJson(closestProduces(method), method.getGenericReturnType()), null);
    }

    /**
     * @return the public {@code invoke(RoutingContext)} method declared by Quarkus's {@code RouteHandler}, or {@code null}
     */
    private static Method findInvoker(Class<?> handlerClass) {
        for (Class<?> current = handlerClass; current != null; current = current.getSuperclass()) {
            if (ROUTE_HANDLER.equals(current.getName())) {
                try {
                    return current.getMethod("invoke", RoutingContext.class);
                } catch (NoSuchMethodException e) {
                    return null;
                }
            }
        }
        return null;
    }

    private static Method findRouteMethod(Class<?> beanClass, String methodName) {
        for (Class<?> current = beanClass; current != null && current != Object.class; current = current.getSuperclass()) {
            for (Method candidate : current.getDeclaredMethods()) {
                if (candidate.getName().equals(methodName) && !candidate.isSynthetic() && !routes(candidate).isEmpty()) {
                    return candidate;
                }
            }
        }
        return null;
    }

    /**
     * @return the {@code @Route} annotations of the method, unwrapping the repeatable container
     */
    private static List<Annotation> routes(Method method) {
        return Arrays.stream(method.getAnnotations())
                .flatMap(annotation -> switch (annotation.annotationType().getName()) {
                    case ROUTE -> Stream.of(annotation);
                    case ROUTES -> Arrays.stream((Annotation[]) attribute(annotation, "value"));
                    default -> Stream.empty();
                })
                .toList();
    }

    /**
     * @return the closest {@code produces} values: the first route declaring some, else the {@code @RouteBase}'s
     */
    private static String[] closestProduces(Method method) {
        for (Annotation route : routes(method)) {
            String[] produces = (String[]) attribute(route, "produces");
            if (produces != null && produces.length > 0) {
                return produces;
            }
        }
        for (Annotation annotation : method.getDeclaringClass().getAnnotations()) {
            if (ROUTE_BASE.equals(annotation.annotationType().getName())) {
                return (String[]) attribute(annotation, "produces");
            }
        }
        return new String[0];
    }

    /**
     * Reads an annotation attribute reflectively, so the runtime module needs no reactive-routes dependency.
     */
    private static Object attribute(Annotation annotation, String name) {
        try {
            return annotation.annotationType().getMethod(name).invoke(annotation);
        } catch (ReflectiveOperationException e) {
            return null;
        }
    }

    private static List<String> annotationNames(Annotation[] annotations) {
        return Arrays.stream(annotations).map(annotation -> annotation.annotationType().getName()).toList();
    }

    /**
     * Reads the targeting rules from the configuration rather than from CDI: an application without Quarkus REST may
     * have no bean injecting the mapping, which then would not be exposed as a bean.
     */
    private static TargetRules targetRules() {
        return TargetRules.of(ConfigProvider.getConfig().unwrap(SmallRyeConfig.class)
                .getConfigMapping(GoblinTargetingConfig.class));
    }

    /**
     * Resolves the engine of the running application on every request, so a dev-mode live reload is never served by
     * the engine of a previous generation.
     */
    private static AssaultEngine engine() {
        ArcContainer container = Arc.container();
        return container != null ? container.instance(AssaultEngine.class).get() : null;
    }

    private static Vertx currentVertx() {
        Context context = Vertx.currentContext();
        return context != null ? context.owner() : null;
    }
}
